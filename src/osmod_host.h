// Copy osmod_host.h and osmod_host.cpp into your project. The OSMod
// builder generates `osmod_registry()`, which calls register_mod() once
// per built-in mod. Your launcher or menu reads mods() to list them, the
// switches turn them on and off, and your file layer asks redirect() and
// replacement() before it opens a game file. A build with no mods links
// against an empty registry and behaves exactly like stock.
#pragma once
#include <atomic>
#include <cstddef>
#include <filesystem>
#include <optional>
#include <span>
#include <string>
#include <string_view>

namespace osmod::host {

struct Redirect {
    const char* from;  // game file path, '/' separated, any case
    const char* to;
};

// Generated by the builder; the layout is part of the spec.
struct ModInfo {
    const char* id;
    const char* name;
    const char* version;
    const char* kind;         // "core" or "mod"
    const char* authors;
    const char* license;
    const char* description;
    const char* hooks;        // one line per site, for display
    const unsigned char* preview;  // PNG bytes, or nullptr
    std::size_t preview_size;
    const Redirect* redirects;     // game path -> other game path
    std::size_t redirect_count;
    const Redirect* replaces;      // game path -> file the mod built, relative to the root
    std::size_t replace_count;
    std::atomic<bool>* enabled;    // nullptr: always on (the core)
};

void register_mod(const ModInfo&);
std::span<const ModInfo* const> mods();

// Switches persist in a small text file (one `id=1` or `id=0` per line).
void load(const std::filesystem::path&);
void save(const std::filesystem::path&);
void set_enabled(const ModInfo&, bool);
inline bool enabled(const ModInfo& mod) { return !mod.enabled || mod.enabled->load(std::memory_order_relaxed); }

// The folder that replacement paths are relative to (usually the game's).
void set_root(const std::filesystem::path&);
// Take a fresh copy of the enabled mods' file changes. Call it when the
// game starts, so file switches apply on the next start.
void apply_files();
// Game path -> game path to open instead (or the same path).
std::string redirect(std::string relative);
// Host file to read instead of a game path, if an enabled mod built one.
std::optional<std::filesystem::path> replacement(const std::string& relative);
std::size_t redirects_served();
std::size_t redirects_active();

}  // namespace osmod::host
